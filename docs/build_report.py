def H(text, lvl=1):
    doc.add_heading(text, level=lvl)


def P(text="", bold=False, italic=False, size=None, align=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold, r.italic = bold, italic
    if size:
        r.font.size = Pt(size)
    if align:
        p.alignment = align
    return p


def B(text):
    p = doc.add_paragraph(text, style='List Bullet')
    p.paragraph_format.space_after = Pt(2)
    return p


def _cell(cell, text, size, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT):
    cell.text = ""
    cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
    p = cell.paragraphs[0]
    p.alignment = align
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2)
    run = p.add_run(str(text))
    run.bold = bold
    run.font.size = Pt(size)


def TABLE(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Light Grid Accent 1'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, h in enumerate(headers):
        _cell(t.rows[0].cells[i], h, CELL, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            # คอลัมน์แรกที่เป็นตัวเลขล้วน เช่น ลำดับหรือรหัสเคส จัดกึ่งกลางอ่านง่ายกว่า
            numeric = i == 0 and str(v).strip().isdigit()
            _cell(cells[i], v, CELL,
                  align=WD_ALIGN_PARAGRAPH.CENTER if numeric else WD_ALIGN_PARAGRAPH.LEFT)
    if widths:
        for r_ in t.rows:
            for i, w in enumerate(widths):
                r_.cells[i].width = Cm(w)
    doc.add_paragraph()
    return t


def IMAGE(name, caption, width_cm=16):
    path = IMG / name
    if path.exists():
        doc.add_picture(str(path), width=Cm(width_cm))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        P(caption, italic=True, size=12, align=WD_ALIGN_PARAGRAPH.CENTER)
        return True
    return False


