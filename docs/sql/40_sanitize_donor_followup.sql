-- 40. ล้างข้อมูลส่วนตัวจริงที่หลุดเข้ามาหลังไฟล์ 37
--
-- ไฟล์ 37 ล้างข้อมูลไปแล้วรอบหนึ่ง แต่หลังจากนั้นมีการเพิ่มผู้บริจาค
-- ใหม่ด้วยชื่อ-นามสกุลจริงและเบอร์มือถือจริง ซึ่งขึ้นเป็นแถวแรก
-- ของหน้า /donors (เรียงตามจำนวนครั้งที่บริจาค)
--
-- ใช้วิธี "เปลี่ยนชื่อ" ไม่ใช่ "ลบ" เพราะผู้บริจาครายนี้มีประวัติบริจาค
-- อยู่แล้ว และ donations_donor_id_fkey เป็น ON DELETE SET NULL
-- ถ้าลบทิ้ง ใบรับของที่ออกไปแล้วจะกลายเป็นไม่มีชื่อผู้บริจาค
-- =================================================================

update public.donors
   set name    = 'คุณลลิตา ใจบุญ',
       phone   = '000-000-0020',
       address = 'ท่าศาลา นครศรีธรรมราช'
 where id = '4e5eacc6-e7cc-4909-9366-26636254b4c4';

-- ตรวจผล: ต้องไม่เหลือเบอร์ที่ไม่ใช่รูปแบบตัวอย่าง 000-000-XXXX
select id, name, phone, address
  from public.donors
 where phone is not null
   and phone !~ '^000-000-[0-9]{4}$';

-- -----------------------------------------------------------------
-- จัดรูปแบบเบอร์ของบัญชีทดสอบ somchai ให้ตรงกับเบอร์ตัวอย่างอื่น
-- (เบอร์เดิม 0987654321 เป็นเลขเรียงชัดเจนว่าปลอมอยู่แล้ว
--  แต่รูปแบบไม่ตรงกับ 081-234-56XX ที่บัญชีอื่นใช้)
-- -----------------------------------------------------------------

update public.profiles
   set phone = '081-234-5684'
 where username = 'somchai';

-- ตรวจผล: ทุกบัญชีต้องเป็นรูปแบบ 08X-XXX-XXXX
select username, full_name, phone
  from public.profiles
 where phone is not null
 order by username;
