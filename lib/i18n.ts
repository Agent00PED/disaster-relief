export type TranslationValues = Record<string, string | number>

export function translate(language: Language, text: string, values: TranslationValues = {}) {
  const message = language === 'en' && Object.hasOwn(english, text) ? english[text] : text
  return message.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : placeholder,
  )
}

export function formatDate(language: Language, value: string) {
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return value
  return new Intl.DateTimeFormat(language === 'en' ? 'en-GB' : 'th-TH', {
    day: 'numeric', month: 'short', year: 'numeric', timeZone: 'Asia/Bangkok',
  }).format(date)
}

