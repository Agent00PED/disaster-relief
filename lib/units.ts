/**
 * แปลงหน่วยที่ผู้ใช้เคยพิมพ์เอง ให้เป็นคำมาตรฐานในรายการ UNITS
 * ค่าที่ไม่รู้จักจะคืนกลับไปเหมือนเดิม (แค่ตัดช่องว่างหัวท้าย) ไม่ทิ้งข้อมูล
 */
export function normalizeUnit(unit: string | null | undefined) {
  const u = (unit ?? '').trim()
  if (!u) return ''
  if ((UNITS as readonly string[]).includes(u)) return u
  return UNIT_ALIAS[u] ?? UNIT_ALIAS[u.toLowerCase()] ?? u
}

export function unitLabel(unit: string | null | undefined, locale: string) {
  const u = (unit ?? '').trim()
  return locale === 'en' ? (UNIT_EN[u] ?? u) : u
}
